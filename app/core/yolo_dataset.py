"""YOLO dataset export helpers.

The UI keeps source annotations next to each image for editing. This module
creates a portable, training-ready YOLO dataset without modifying that source
folder.
"""
from __future__ import annotations

import json
import os
import random
import shutil
from pathlib import Path

from PIL import Image


def class_names_from_items(items: list) -> list[str]:
    """Return a stable first-seen list of non-empty box labels."""
    names = []
    seen = set()
    for item in items:
        for box in getattr(item, "boxes", []) or []:
            label = str(getattr(box, "label", "")).strip()
            if label and label not in seen:
                seen.add(label)
                names.append(label)
    return names


def read_class_names(path: str) -> list[str]:
    """Read one class name per line, ignoring blank lines and duplicates."""
    if not os.path.isfile(path):
        return []
    names = []
    seen = set()
    with open(path, "r", encoding="utf-8-sig") as f:
        for line in f:
            label = line.strip()
            if label and label not in seen:
                seen.add(label)
                names.append(label)
    return names


def _atomic_write(path: str, content: str):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(content)
    os.replace(tmp, path)


def write_data_yaml(dataset_root: str, names: list[str], output_path: str | None = None) -> str:
    """Write a portable Ultralytics-compatible data.yaml.

    The generated dataset layout is images/train, images/val, labels/train and
    labels/val, so the YAML can use a relative ``path: .`` and remain portable
    when the dataset folder is moved to another machine.
    """
    root = os.path.abspath(dataset_root)
    clean_names = []
    seen = set()
    for name in names:
        label = str(name).strip()
        if label and label not in seen:
            seen.add(label)
            clean_names.append(label)
    if not clean_names:
        raise ValueError("至少需要一个检测类别")
    output = output_path or os.path.join(root, "data.yaml")
    lines = [
        "# Generated by TagForge",
        "path: .",
        "train: images/train",
        "val: images/val",
        "names:",
    ]
    for index, label in enumerate(clean_names):
        lines.append(f"  {index}: {json.dumps(label, ensure_ascii=False)}")
    _atomic_write(output, "\n".join(lines) + "\n")
    return output


def _unique_relative_path(relative: str, used: set[str]) -> str:
    """Avoid image/label collisions while preserving source subdirectories."""
    path = Path(relative)
    candidate = path.as_posix()
    key = candidate.casefold()
    if key not in used:
        used.add(key)
        return candidate
    counter = 1
    while True:
        candidate_path = path.with_name(f"{path.stem}__{counter}{path.suffix}")
        candidate = candidate_path.as_posix()
        key = candidate.casefold()
        if key not in used:
            used.add(key)
            return candidate
        counter += 1


def _box_row(box, width: int, height: int, class_to_id: dict[str, int]) -> str | None:
    label = str(getattr(box, "label", "")).strip()
    if not label or label not in class_to_id:
        return None
    x1, x2 = sorted((float(box.x1), float(box.x2)))
    y1, y2 = sorted((float(box.y1), float(box.y2)))
    x1 = max(0.0, min(float(width), x1))
    x2 = max(0.0, min(float(width), x2))
    y1 = max(0.0, min(float(height), y1))
    y2 = max(0.0, min(float(height), y2))
    cx = ((x1 + x2) / 2.0) / width
    cy = ((y1 + y2) / 2.0) / height
    bw = (x2 - x1) / width
    bh = (y2 - y1) / height
    return f"{class_to_id[label]} {cx:.6f} {cy:.6f} {bw:.6f} {bh:.6f}"


def _write_item_labels(path: str, item, class_to_id: dict[str, int]):
    with Image.open(item.path) as image:
        width, height = image.size
    rows = []
    for box in getattr(item, "boxes", []) or []:
        row = _box_row(box, width, height, class_to_id)
        if row:
            rows.append(row)
    _atomic_write(path, "\n".join(rows) + ("\n" if rows else ""))


def split_yolo_dataset(items: list, source_root: str, output_root: str,
                       train_ratio: float = 0.8, seed: int = 42) -> dict:
    """Copy images and annotations into a standard train/val YOLO layout.

    The source folder is never modified. Empty label files are written for
    images without boxes so negative samples remain part of the dataset.
    """
    if not items:
        raise ValueError("当前没有图片可划分")
    if not 0.0 < float(train_ratio) < 1.0:
        raise ValueError("训练集比例必须在 0 和 1 之间")
    source = os.path.abspath(source_root)
    output = os.path.abspath(output_root)
    try:
        common = os.path.commonpath((source, output))
    except ValueError:
        common = ""
    if common == source or common == output:
        raise ValueError("输出目录不能位于当前图片目录内，请选择外部空目录")

    output_path = Path(output)
    if output_path.exists():
        existing = list(output_path.iterdir())
        if existing:
            raise FileExistsError("输出目录必须为空，以避免覆盖已有数据集")
    output_path.mkdir(parents=True, exist_ok=True)

    ordered = sorted(items, key=lambda item: os.path.abspath(item.path).casefold())
    # 类别编号先固定，再打乱图片，保证不同随机种子不会改变 class_id。
    names = class_names_from_items(ordered)
    if not names:
        raise ValueError("当前图片没有检测框标签，无法生成 YOLO 类别表")
    class_to_id = {name: index for index, name in enumerate(names)}
    rng = random.Random(seed)
    rng.shuffle(ordered)
    total = len(ordered)
    if total == 1:
        train_count = 1
    else:
        train_count = max(1, min(total - 1, int(total * float(train_ratio) + 0.5)))
    groups = [("train", ordered[:train_count]), ("val", ordered[train_count:])]
    for split, group in groups:
        used = set()
        for item in group:
            relative = os.path.relpath(item.path, source)
            if relative.startswith(".."):
                relative = os.path.basename(item.path)
            relative = _unique_relative_path(relative, used)
            image_target = output_path / "images" / split / Path(relative)
            label_target = output_path / "labels" / split / Path(relative).with_suffix(".txt")
            image_target.parent.mkdir(parents=True, exist_ok=True)
            label_target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(item.path, image_target)
            _write_item_labels(str(label_target), item, class_to_id)

    _atomic_write(str(output_path / "classes.txt"), "\n".join(names) + "\n")
    return {
        "total": total,
        "train": len(groups[0][1]),
        "val": len(groups[1][1]),
        "classes": names,
        "output": str(output_path),
    }